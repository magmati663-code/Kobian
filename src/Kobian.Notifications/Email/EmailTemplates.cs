    public static string Get(string language, string key) =>
        (language == "en" ? En : Pl).TryGetValue(key, out var v) ? v : throw new KeyNotFoundException("Missing e-mail template key.");

    public static bool Has(string language, string key) => (language == "en" ? En : Pl).ContainsKey(key);

    internal static IEnumerable<string> Keys(string language) => (language == "en" ? En : Pl).Keys;
