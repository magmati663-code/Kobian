#!/usr/bin/env python3
"""
Rejestr kodów KB (D1.8, BL-4): dodawanie wpisów i generowanie src/Kobian.Domain/KbCode.cs z docs/kb-codes.yaml.
  python3 tools/kb.py add KB-2105 AccessDenied permanent error "PL" "EN" "akcja" "action EN" "źródło"
  python3 tools/kb.py gen
  python3 tools/kb.py docs   (docs/kb-codes.md)
  python3 tools/kb.py resx   (src/Kobian.UI/Resources/KbMessages*.resx)
Format YAML jest ograniczony (płaskie mapy, wartości w cudzysłowach) — parser poniżej, bez bibliotek.
"""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
YAML = os.path.join(ROOT, 'docs', 'kb-codes.yaml')
OUT = os.path.join(ROOT, 'src', 'Kobian.Domain', 'KbCode.cs')
CLASSES = {'transient', 'permanent', 'integrity', 'security'}


def parse():
    text = open(YAML, encoding='utf-8').read()
    entries = []
    for block in text.split('\n- ')[1:]:
        e = {}
        for line in ('  ' + block).split('\n'):
            m = re.match(r'^\s+([a-z.]+): (.*)$', line)
            if m:
                v = m.group(2).strip()
                if v.startswith('"') and v.endswith('"'): v = v[1:-1]
                e[m.group(1)] = v
        entries.append(e)
    return text, entries


def gen():
    _, entries = parse()
    names, codes = set(), set()
    lines = ['// <auto-generated> tools/kb.py gen — z docs/kb-codes.yaml (D1.8). Nie edytuj ręcznie. </auto-generated>',
             '#nullable enable', 'namespace Kobian.Domain;', '', '/// <summary>Kody błędów z rejestru docs/kb-codes.yaml (D1.8).</summary>',
             'public static class KbCode', '{']
    for e in sorted(entries, key=lambda e: e['code']):
        assert re.fullmatch(r'KB-\d{4}', e['code']), e
        assert e.get('class') in CLASSES, e
        assert e.get('action.en'), e  # it. 124: każda akcja ma wersję EN
        assert e['name'] not in names and e['code'] not in codes, e
        names.add(e['name']); codes.add(e['code'])
        lines.append(f'    /// <summary>{e["message.pl"]}</summary>')
        lines.append(f'    public const string {e["name"]} = "{e["code"]}";')
        lines.append('')
    # it. 103: zbiór wszystkich kodów — walidacja kodów z niezaufanych źródeł (np. odpowiedź procesu Worker, D2.8)
    lines.append('    private static readonly System.Collections.Generic.HashSet<string> AllCodes = new(System.StringComparer.Ordinal)')
    lines.append('    {')
    for e in sorted(entries, key=lambda e: e['code']):
        lines.append(f'        {e["name"]},')
    lines.append('    };')
    lines.append('')
    lines.append('    /// <summary>Czy kod jest w rejestrze (porównanie porządkowe).</summary>')
    lines.append('    public static bool IsKnown(string? code) => code is not null && AllCodes.Contains(code);')
    lines.append('}')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('KbCode.cs:', len(entries), 'kodów')


def add(code, name, cls, sev, pl, en, action, action_en, source):
    text, entries = parse()
    if any(e['code'] == code for e in entries): sys.exit(f'{code} już istnieje')
    if any(e['name'] == name for e in entries): sys.exit(f'{name} już istnieje')
    assert cls in CLASSES
    for s in (pl, en, action, action_en, source): assert '"' not in s and action_en
    text = text.rstrip('\n') + f'''

- code: {code}
  name: {name}
  class: {cls}
  severity: {sev}
  message.pl: "{pl}"
  message.en: "{en}"
  action: "{action}"
  action.en: "{action_en}"
  source: "{source}"
  since: "0.1"
'''
    open(YAML, 'w', encoding='utf-8').write(text)
    gen()


def docs():
    _, entries = parse()
    out = ['# Kody błędów KB (generowane: tools/kb.py docs — nie edytuj ręcznie)', '',
           'Źródło: `docs/kb-codes.yaml` (D1.8). Klasa: przejściowy/trwały/integralność/bezpieczeństwo (4.7).', '',
           '| Kod | Klasa | Waga | Komunikat (PL) | Message (EN) | Akcja | Action (EN) | Źródło |', '|---|---|---|---|---|---|---|---|']
    for e in sorted(entries, key=lambda e: e['code']):
        out.append(f"| {e['code']} | {e['class']} | {e['severity']} | {e['message.pl']} | {e['message.en']} | {e['action']} | {e['action.en']} | {e['source']} |")
    open(os.path.join(ROOT, 'docs', 'kb-codes.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('kb-codes.md:', len(entries))


def resx():
    """KbMessages.resx (PL, neutralny) i KbMessages.en.resx (EN) dla UI/CLI (R2.6.5)."""
    from xml.sax.saxutils import escape
    _, entries = parse()
    head = ('<?xml version="1.0" encoding="utf-8"?>\n<root>\n'
            '  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>\n'
            '  <resheader name="version"><value>2.0</value></resheader>\n'
            '  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>\n'
            '  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>\n')
    d = os.path.join(ROOT, 'src', 'Kobian.UI', 'Resources')
    os.makedirs(d, exist_ok=True)
    for suffix, field, afield in (('', 'message.pl', 'action'), ('.en', 'message.en', 'action.en')):
        out = [head]
        for e in sorted(entries, key=lambda e: e['code']):
            k = e['code'].replace('-', '_')
            out.append(f'  <data name="{k}_Message" xml:space="preserve"><value>{escape(e[field])}</value></data>\n')
            out.append(f'  <data name="{k}_Action" xml:space="preserve"><value>{escape(e[afield])}</value></data>\n')
        out.append('</root>\n')
        open(os.path.join(d, f'KbMessages{suffix}.resx'), 'w', encoding='utf-8').write(''.join(out))
    print('resx:', len(entries))


if __name__ == '__main__':
    a = sys.argv[1:]
    if a and a[0] == 'gen': gen()
    elif a and a[0] == 'docs': docs()
    elif a and a[0] == 'resx': resx()
    elif a and a[0] == 'add' and len(a) == 10: add(*a[1:])
    else: sys.exit(__doc__)
